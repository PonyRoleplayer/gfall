static int group(int climate)
{
    switch (climate) {
    case CLIMATE_DESERT:
    case CLIMATE_DESERT2:
        return G_DESERT;
    case CLIMATE_MOUNTAIN:
    case CLIMATE_MOUNTAIN_WOODS:
        return G_MOUNTAINS;
    case CLIMATE_RAINFOREST:
        return G_JUNGLE;
    case CLIMATE_OCEAN:
    case CLIMATE_SWAMP:
        return G_SWAMP;
    case CLIMATE_SUBTROPICAL:
        return G_SUBTROPICAL;
    default:
        return G_WOODLANDS;
    }
}

