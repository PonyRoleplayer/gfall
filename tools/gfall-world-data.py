#!/usr/bin/env python3
"""Extract original travel constants from the verified, byte-matched executable."""
import argparse
import hashlib
import struct
import sys
from pathlib import Path
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('decomp', type=Path)
parser.add_argument('executable', type=Path)
a = parser.parse_args()
if hashlib.sha1(a.executable.read_bytes()).hexdigest() != (a.decomp/'config/fall.sha1').read_text().split()[0]:
    parser.error('FALL.EXE does not match the reference')
sys.path.insert(0,str(a.decomp/'tools'))
from le import LE
image = LE(a.executable)
objects = image.load(relocate=True)
symbols = {}
for line in (a.decomp/'config/symbols.txt').read_text().splitlines():
    if ' = 0x' in line:
        name, value = line.split(' = ',1)
        symbols[name] = int(value.split(';')[0],16)
def values(symbol, fmt, offset=0):
    address = symbols[symbol]+offset
    obj = image.obj_of_va(address)
    return struct.unpack_from('<'+fmt,objects[obj.index],address-obj.base)
text = '/* Generated by tools/gfall-world-data.py from verified FALL.EXE. */\n'
for name, symbol, fmt, offset in [('g_travel_terrain','terrain_travel_modifiers','6i',0),('g_climate_category','climate_categories','10B',223)]:
    data = values(symbol,fmt,offset)
    text += 'static const int %s[] = {%s};\n' % (name,', '.join(map(str,data)))
Path('src/game/dagger/tables/traveldata.h').write_text(text)
