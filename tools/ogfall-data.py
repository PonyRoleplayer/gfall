#!/usr/bin/env python3
"""Extract OGFALL's immutable item data from the byte-perfect FALL.EXE.

Authoring tool, not a build dependency. Uses the reference project's LE reader:
  python3 tools/ogfall-data.py /path/to/daggerfall-decomp daggerfall/DAGGER/FALL.EXE
The addresses and layouts are named in that project's config/symbols.txt,
include/structs.h, and src/lifted/equip.c. Never rewrites ARENA2.
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('decomp', type=Path, help='byte-perfect reference checkout')
parser.add_argument('executable', type=Path, help='original FALL.EXE (1.07.213)')
args = parser.parse_args()
expected = (args.decomp / 'config/fall.sha1').read_text().split()[0]
if hashlib.sha1(args.executable.read_bytes()).hexdigest() != expected:
    parser.error('FALL.EXE does not match the reference checkout checksum')
sys.path.insert(0, str(args.decomp / 'tools'))
from le import LE
image = LE(args.executable)
objects = image.load(relocate=True)

def read(address, size):
    obj = image.obj_of_va(address)
    offset = address - obj.base
    return objects[obj.index][offset:offset + size]

def unpack(address, fmt):
    return struct.unpack('<' + fmt, read(address, struct.calcsize('<' + fmt)))

def array(name, values, ctype='df_u8'):
    return 'static const %s %s[] = { %s };\n' % (ctype, name, ', '.join(map(str, values)))

out = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n',
       'static const OgItemDef g_template[288] = {\n']
for i in range(288):
    b = read(0x17d22a + i * 48, 48)
    name = b[:24].split(b'\0')[0].decode('cp437')
    weight = struct.unpack_from('<i', b, 24)[0]
    condition = struct.unpack_from('<H', b, 28)[0]
    value = struct.unpack_from('<I', b, 34)[0]
    dropped, inventory = struct.unpack_from('<HH', b, 44)
    values = [weight, condition, value, b[41], b[42], b[43], dropped, inventory]
    out.append('    {%s, %s}, /* %d */\n' % (json.dumps(name), ', '.join(map(str, values)), i))
out.append('};\n')
for group in range(29):
    address, = unpack(0x185f88 + group * 4, 'I')
    values = []
    if address:
        for i in range(100):
            value, = unpack(address + i * 2, 'h')
            if value < 0:
                break
            values.append(value)
    out.append(array('g_group%d' % group, values + [65535], 'df_u16'))
out.append('static const df_u16 *g_groups[29] = {\n    ' + ', '.join('g_group%d' % g for g in range(29)) + '\n};\n')
for name, address, count, fmt in [
    ('g_male_slot',0x1860da,41,'B'), ('g_female_slot',0x186104,35,'B'),
    ('g_shape',0x186589,8,'B'), ('g_start_spell',0x17bb3f,42,'B'),
    ('g_loot_group',0x1861aa,15,'B'), ('g_dungeon_loot',0x1865f2,19,'B'), ('g_share',0x186591,10,'B'),
    ('g_value',0x1869c0,10,'H'), ('g_weight',0x1869d4,10,'H'),
    ('g_condition',0x1869ea,10,'H')]:
    out.append(array(name, unpack(address, str(count) + fmt), 'df_u16' if fmt == 'H' else 'df_u8'))
out.append('static const df_u16 g_loot[21][15] = {\n')
for i in range(21):
    address, = unpack(0x18642f + i * 4, 'I')
    out.append('    {' + ', '.join(map(str,unpack(address,'15H'))) + '},\n')
out.append('};\n')
symbols = dict()
for line in (args.decomp/'config/symbols.txt').read_text().splitlines():
    if ' = 0x' in line:
        name, value = line.split(' = ', 1)
        symbols[name] = int(value.split(';')[0], 16)
# Book entries are {id, rarity}; include IDs, retaining the source order.
book_dir = args.executable.parent / 'ARENA2' / 'BOOKS'
book_ids = sorted(int(p.stem[3:]) for p in book_dir.glob('BOK*.TXT'))
out.append(array('g_book', book_ids, 'df_u16'))
out.append(array('g_book_rarity', [struct.unpack_from('<h', (book_dir / ('BOK%05d.TXT' % i)).read_bytes(), 228)[0] - 1
                                  for i in book_ids], 'df_i16'))
out.append(array('g_dye_ranges', unpack(0x1886a8,'32B')))
out.append(array('g_dye_metal', unpack(0x1886d2,'160B')))
out.append(array('g_pants_dye', unpack(0x18659b,'4B')))
out.append(array('g_sash_dye', unpack(0x18659f,'4B')))
out.append(array('g_male_style', unpack(0x18606b,'111B')))
out.append(array('g_female_style', unpack(0x185ffc,'111B')))
out.append(array('g_armor_base', unpack(0x185128,'3h'), 'df_i16'))
out.append(array('g_armor_slot', unpack(0x18513e,'7B')))
out.append(array('g_shield_part', unpack(0x18512e,'16B')))
out.append(array('g_material_hit', unpack(symbols['material_to_hit'],'10h'), 'df_i16'))
out.append(array('g_proficiency', unpack(0x18867d, '19H'), 'df_u16'))
out.append(array('g_group_tab', unpack(symbols['item_group_tab'],'29B')))
out.append(array('g_weapon_sound', unpack(0x188208,'19h'), 'df_i16'))
out.append(array('g_damage_min', [unpack(symbols['weapon_damage_min']+i*4,'h')[0] for i in range(19)], 'df_i16'))
out.append(array('g_damage_max', [unpack(symbols['weapon_damage_max']+i*4,'h')[0] for i in range(19)], 'df_i16'))
out.append(array('g_condition_threshold', unpack(symbols['condition_thresholds'],'8B')))
out.append(array('g_effect_text', unpack(symbols['spell_effect_text_base'],'51h'), 'df_i16'))
out.append('static const char *g_condition_name[8] = {\n')
for i in range(8):
    pointer, = unpack(symbols['condition_names']+i*4,'I')
    out.append('    '+json.dumps(read(pointer,100).split(b'\0')[0].decode('cp437'))+',\n')
out.append('};\n')
out.append('static const char *g_effect_subtype[51][12] = {\n')
for group in range(51):
    names = []
    for pointer in unpack(symbols['spell_effect_subtype_names']+group*48,'12I'):
        names.append(json.dumps(read(pointer,100).split(b'\0')[0].decode('cp437')) if pointer else '0')
    out.append('    {'+', '.join(names)+'},\n')
out.append('};\n')
out.append('static const char *g_effect_name[51] = {\n')
for i in range(51):
    address, = unpack(0x182686 + i * 4, 'I')
    name = read(address, 100).split(b'\0')[0].decode('cp437') if address else ''
    out.append('    ' + json.dumps(name) + ',\n')
out.append('};\n')
Path('src/game/ogfall/tables/itemdata.h').write_text(''.join(out))

# Combat data belongs to OGFALL as well: no DFU combat tables at runtime.
arena = args.executable.parent / 'ARENA2'
raw = (arena / 'MONSTER.BSA').read_bytes()
count, kind = struct.unpack_from('<HH', raw)
assert kind == 0x100
records, cursor = {}, 4
for i in range(count):
    entry = len(raw) - count * 18 + i * 18
    name = raw[entry:entry + 14].split(b'\0')[0].decode('ascii')
    size, = struct.unpack_from('<I', raw, entry + 14)
    records[name] = raw[cursor:cursor + size]
    cursor += size

out = ['/* Generated by tools/ogfall-data.py from FALL.EXE and MONSTER.BSA. */\n']
out.append(array('g_nav_angle',unpack(0x186a14,'8i'),'df_i32'))
out.append('static const df_u8 g_encounter[45][20] = {\n')
for pointer in unpack(symbols['encounter_tables'],'45I'):
    out.append('    {' + ', '.join(map(str,unpack(pointer,'20B'))) + '},\n')
out.append('};\n')
for name, symbol, count, fmt in [
    ('g_cif', 'weapon_cif_by_index', 18, 'B'),
    ('g_swing', 'weapon_swing_types', 16, 'B'),
    ('g_swing_hit', 'swing_to_hit_mods', 16, 'h'),
    ('g_swing_damage', 'swing_damage_mods', 16, 'h'),
    ('g_weapon_skill', 'weapon_skills', 19, 'B'),
    ('g_body_part', 'struck_body_part_table', 20, 'B'),
    ('g_corpse', 'monster_corpse_textures', 86, 'H'),
    ('g_swing_sound', 'weapon_swing_sounds', 19, 'h'),
    ('g_parry', 'monster_parry_ids', 28, 'B'),
    ('g_weight', 'monster_weights', 43, 'h'),
    ('g_class_kind', 'class_creature_types', 19, 'B'),
    ('g_category', 'monster_category', 43, 'B')]:
    out.append(array(name, unpack(symbols[symbol], str(count) + fmt), 'df_i16' if fmt == 'h' else 'df_u16' if fmt == 'H' else 'df_u8'))
out.append('static const df_u16 g_monster[60][3] = {\n')
for i in range(60):
    row = read(symbols['monster_table'] + i * 29, 29)
    out.append('    {%d, %d, %d},\n' % (row[0],row[2],struct.unpack_from('<H',row,4)[0]))
out.append('};\n')
out.append('static const OgFoeDef g_foe[43] = {\n')
for i in range(43):
    row = read(symbols['monster_table'] + i * 29, 29)
    career = records['ENEMY%03d.CFG' % i]
    name = career[28:44].split(b'\0')[0].decode('cp437')
    damage = struct.unpack_from('<10H', row, 6)
    out.append('    {%s, %d, %d, %d, %d, %d, %d, %d, {%s}, {%s}, {%s}},\n' % (
        json.dumps(name), career[52], row[0], ((row[1] * 5 + 128) % 256) - 128, row[2], row[3],
        struct.unpack_from('<H', row, 4)[0], row[28],
        ', '.join(map(str,struct.unpack_from('<8h', career,58))),
        ', '.join(map(str,damage[::2])), ', '.join(map(str,damage[1::2]))))
out.append('};\n')
# Preserve the original animation scripts, including their strike/missile events.
for i in range(43):
    out.append(array('g_anim%d' % i, records['ASCR%04d.ANC' % i]))
for i in range(128,145):
    out.append(array('g_anim%d' % i, records['ASCR%04d.ANC' % i]))
out.append('static const OgAnimScript g_anim[60] = {\n')
for i in list(range(43)) + list(range(128,145)):
    out.append('    {g_anim%d, sizeof(g_anim%d)},\n' % (i,i))
out.append('};\n')
Path('src/game/ogfall/tables/combatdata.h').write_text(''.join(out))

# lock_show_difficulty / lockpick_door: the exact messages and ordering.
out = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n',
       'static const char *const g_lock_text[17] = {\n']
for pointer in unpack(0x183258, '17I'):
    message = read(pointer, 160).split(b'\0')[0].decode('cp437')
    out.append('    ' + json.dumps(message) + ',\n')
out.append('};\n')
Path('src/game/ogfall/tables/doordata.h').write_text(''.join(out))
Path('src/game/ogfall/tables/progressdata.h').write_text(
    '/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n' +
    array('g_skill_advance',unpack(symbols['skill_advance_multipliers'],'35h'),'df_i16'))

# shop_generate_stock (src/lifted/equip.c 755): per building type (0..20), which item groups its
# shelves draw from, by the shop's variant: 3, 12, 12, 5 or 11 groups each, 0-terminated.
shop = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n']
for name, address, width in [('g_shop_v0', 0x186639, 3), ('g_shop_v2', 0x186678, 12),
                             ('g_shop_v4', 0x186774, 12), ('g_shop_v11', 0x186870, 5),
                             ('g_shop_v15', 0x1868d9, 11)]:
    rows = [unpack(address + t * width, '%dB' % width) for t in range(21)]
    shop.append('static const df_u8 %s[21][%d] = {\n' % (name, width))
    for row in rows:
        shop.append('    {' + ', '.join(map(str, row)) + '},\n')
    shop.append('};\n')
Path('src/game/ogfall/tables/shopdata.h').write_text(''.join(shop))

# holiday_today (src/lifted/parse.c 1920): 53 holidays, each a day of the year and a region + 1 (255 for all).
Path('src/game/ogfall/tables/holidaydata.h').write_text(
    '/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n' +
    array('g_holiday_day', unpack(symbols['holiday_days'], '53h'), 'df_i16') +
    array('g_holiday_region', unpack(symbols['holiday_regions'], '53B')))

# macro_dat_date (src/lifted/parse.c 448): "%s the %d%s of %s" from day, ordinal and month names.
def names(symbol, count):
    out = []
    for pointer in unpack(symbols[symbol], '%dI' % count):
        out.append(json.dumps(read(pointer, 40).split(b'\0')[0].decode('cp437')))
    return out
date = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n']
for name, symbol, count in [('g_day_name', 'day_names', 7), ('g_month_name', 'month_names', 12), ('g_ordinal', 'ordinal_suffixes', 4)]:
    date.append('static const char *const %s[%d] = { %s };\n' % (name, count, ', '.join(names(symbol, count))))
Path('src/game/ogfall/tables/datedata.h').write_text(''.join(date))

# The tavern (src/lifted/tavern.c): the food list, its prices, and the original's own lines.
def cstring(address):
    return json.dumps(read(address, 160).split(b'\0')[0].decode('cp437'))
lodging = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n']
lodging.append('static const char *const g_food_name[11] = { %s };\n' % ', '.join(
    cstring(p) for p in unpack(symbols['tavern_food_names'], '11I')))
lodging.append(array('g_food_price', unpack(symbols['tavern_food_prices'], '11B')))
lodging.append('static const char g_msg_knight[] = %s;\n' % cstring(0x170572))
lodging.append('static const char g_msg_heart[] = %s;\n' % cstring(0x17059d))
lodging.append('static const char g_msg_not_hungry[] = %s;\n' % cstring(0x1705be))
lodging.append('static const char g_msg_no_room[] = %s;\n' % cstring(unpack(0x185087, 'I')[0]))
Path('src/game/ogfall/tables/lodgingdata.h').write_text(''.join(lodging))
Path('src/game/ogfall/tables/lodgingdata.h').write_text(''.join(lodging) +
    'static const char g_msg_expired[] = %s;\n' % cstring(0x1760b1))

# The law (src/lifted/crime.c, src/hand/func_00020C87.c): each crime's reputation loss and fine row, and its name.
# A fine row is {multiplier, base, least, most}; crime ids run 1..13 and the table is indexed by id - 1.
law = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n']
law.append(array('g_crime_loss', unpack(symbols['crime_reputation_loss'], '13i'), 'df_i32'))
law.append('static const df_i16 g_crime_fine[13][4] = {\n')
for i in range(13):
    mul, _pad, base, least, most = unpack(symbols['crime_fine_table'] + i * 8, 'BBhhh')
    law.append('    {%d, %d, %d, %d},\n' % (mul, base, least, most))
law.append('};\n')
law.append('static const char *const g_crime_name[14] = { %s };\n' % ', '.join(
    json.dumps(read(p, 60).split(b'\0')[0].decode('cp437')) for p in unpack(symbols['crime_names'], '14I')))
Path('src/game/ogfall/tables/lawdata.h').write_text(''.join(law))

