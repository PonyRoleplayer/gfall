# Potions (src/lifted/potions.c, equip.c 843): the recipes, 109 bytes each as FALL.EXE keeps them: eight ingredient indices (-2 ends), the value, eight
# ingredient groups, two spare bytes, then the potion's own spell (89 bytes, the layout of SPELLS.STD's records). The table ends at a record with no value.
potion = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n']
recipes = []
while True:
    record = read(symbols['potion_recipes'] + len(recipes) * 109, 109)
    if struct.unpack_from('<H', record, 8)[0] == 0:
        break
    recipes.append(record)
potion.append('#define OG_RECIPES %d\n' % len(recipes))
potion.append('static const unsigned char g_recipe[OG_RECIPES][109] = {\n')
for record in recipes:
    potion.append('    {%s},\n' % ', '.join(str(b) for b in record))
potion.append('};\n')
Path('src/game/ogfall/tables/potiondata.h').write_text(''.join(potion))

