# Stealing (src/lifted/steal.c, src/lifted/inven.c trade_steal_button): the original's own lines.
def cstring_at_pointer(address):
    pointer, = unpack(address, 'I')
    return cstring(pointer)
Path('src/game/ogfall/tables/stealdata.h').write_text(
    '/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n'
    'static const char g_steal_failed[] = %s;\n' % cstring_at_pointer(0x18333c) +
    'static const char g_steal_gold[] = %s;\n' % cstring_at_pointer(0x183340) +
    'static const char g_steal_shop_failed[] = %s;\n' % cstring(0x1771ff) +
    'static const char g_steal_shop_done[] = %s;\n' % cstring(0x177217))
