# Names (src/lifted/names.c, src/hand/func_0008B65C.c): the bank each region's people are named from, the pieces
# shops and taverns are named by, and the fixed words. Lists end at a null pointer; the shop's last words go by
# building type (types 3, 4 and 11 have none).
def string_list(address):
    items = []
    while True:
        pointer, = unpack(address + len(items) * 4, 'I')
        if not pointer:
            return items
        items.append(cstring_text(pointer))

names = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n']
