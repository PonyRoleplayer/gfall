# 4..13 the ten knightly orders, 14..21 the eight temples; kind & 63). Each has the skills that rank it (255-terminated), and 13 message
# records: skill too low, reputation too low, the offer to join, then the line for each of ten ranks. Rank n needs the player's best
# guild skill at the n-th primary step and the next best at the n-th secondary step. The service people are listed by faction id with the
# label the menu shows. The menu's picture is gild0<member>i0.img and its label sits at 159,71.
guild = ['/* Generated by tools/ogfall-data.py from FALL.EXE; do not edit. */\n']
lists = unpack(symbols['guild_skill_lists'], '22I')
guild.append('static const unsigned char g_guild_skills[22][12] = {\n')
for pointer in lists:
    values = []
    for value in read(pointer, 16):
        if value == 255:
            break
        values.append(value)
    guild.append('    {%s},\n' % ', '.join(str(v) for v in values + [255]))
guild.append('};\n')
guild.append('static const df_i16 g_guild_message[22][13] = {\n')
for g in range(22):
    guild.append('    {%s},\n' % ', '.join(map(str, unpack(symbols['guild_messages'] + g * 26, '13h'))))
guild.append('};\n')
guild.append(array('g_rank_primary', unpack(symbols['guild_rank_primary_skill'], '10B')))
guild.append(array('g_rank_secondary', unpack(symbols['guild_rank_secondary_skill'], '10B')))
# The tables hold 89 real entries; the loop in guild_service_label reads three more, whose bytes are other data.
