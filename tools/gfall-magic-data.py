#!/usr/bin/env python3
"""Extract verified FALL.EXE magic/ailment constants; never modifies game data."""
import argparse
import hashlib
import struct
import sys
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('decomp', type=Path)
parser.add_argument('executable', type=Path)
args = parser.parse_args()
if hashlib.sha1(args.executable.read_bytes()).hexdigest() != (args.decomp/'config/fall.sha1').read_text().split()[0]:
    parser.error('FALL.EXE does not match the byte-matched reference')
sys.path.insert(0,str(args.decomp/'tools'))
from le import LE
image = LE(args.executable)
objects = image.load(relocate=True)
symbols = {}
for line in (args.decomp/'config/symbols.txt').read_text().splitlines():
    if ' = 0x' in line:
        name, value = line.split(' = ',1)
        symbols[name] = int(value.split(';')[0],16)
def read(address, fmt):
    obj = image.obj_of_va(address)
    return struct.unpack_from('<'+fmt,objects[obj.index],address-obj.base)
def rows(name, address, count, fmt, ctype):
    stride = struct.calcsize('<'+fmt)
    return 'static const %s %s[%d][%d] = {\n%s};\n' % (ctype,name,count,len(read(address,fmt)), ''.join('    {'+', '.join(map(str,read(address+i*stride,fmt)))+'},\n' for i in range(count)))
def array(name, symbol, fmt, ctype):
    return 'static const %s %s[] = {%s};\n' % (ctype,name,', '.join(str(v)+('u' if ctype == 'df_u32' else '') for v in read(symbols[symbol],fmt)))
out = ['/* Generated by tools/gfall-magic-data.py from verified FALL.EXE. */\n']
for name,symbol,count,fmt,ctype in [
    ('g_effect_flags','spell_effect_settings',51,'12B','df_u8'),
    ('g_cost_index','spell_effect_cost_index',51,'12B','df_u8'),
    ('g_cost','spell_effect_costs',43,'4h','df_i16'),
    ('g_poison','poison_table',12,'4h','df_i16')]:
    out.append(rows(name,symbols[symbol],count,fmt,ctype))
for name,symbol,fmt,ctype in [
    ('g_school','spell_effect_school','51B','df_u8'),
    ('g_formula','spell_effect_cost_formula','51B','df_u8'),
    ('g_school_skill','magic_school_skills','6B','df_u8'),
    ('g_target_factor','spell_target_cost_factor','5h','df_i16'),
    ('g_cast_sound','spell_cast_sounds','5h','df_i16'),
    ('g_impact_sound','spell_impact_sounds','5h','df_i16'),
    ('g_element_bit','spell_element_class_bits','5B','df_u8'),
    ('g_resist_flag','spell_resist_flags','5I','df_u32')]: out.append(array(name,symbol,fmt,ctype))
for name,symbol,count in [('g_bat_disease','monster_diseases_bat',4),('g_mummy_disease','monster_diseases_mummy',12),('g_plague_disease','monster_diseases_plague',2)]:
    out.append(array(name,symbol,str(count)+'B','df_u8'))
spell_lists = [(1,'imp'),(18,'ghost'),(21,'orc_shaman'),(23,'wraith'),(25,'frost_daedra'),(26,'fire_daedra'),(27,'daedroth'),(28,'vampire'),(29,'seducer'),(30,'vampire_ancient'),(31,'daedra_lord'),(32,'lich'),(33,'ancient_lich')]
for kind,name in spell_lists:
    address = symbols['monster_spells_'+name]
    values = []
    for i in range(32):
        value = read(address+i,'B')[0]
        values.append(value)
        if value == 255: break
    out.append('static const df_u8 g_spells%d[] = {%s};\n' % (kind,', '.join(map(str,values))))
out.append('static const df_u8 *g_creature_spells[43] = {'+', '.join('g_spells%d'%kind if any(k==kind for k,n in spell_lists) else '0' for kind in range(43))+'};\n')
class_lists = read(symbols['monster_class_spell_lists'],'7I')
for i,address in enumerate(class_lists):
    values = []
    for j in range(64):
        value = read(address+j,'B')[0]
        values.append(value)
        if value == 255: break
    out.append('static const df_u8 g_class_spells%d[] = {%s};\n' % (i,', '.join(map(str,values))))
out.append('static const df_u8 *g_class_spells[7] = {'+', '.join('g_class_spells%d'%i for i in range(7))+'};\n')
# The spell maker (spells.c, func_00037AB7, func_00038228): which targets an effect allows (0 the caster only, 1 touch and beyond, 2 any), the elemental level of each (0 for none: only effects above 0 let the player pick an element) and the names of each effect's subtypes.
out.append('static const df_u8 g_target_class[] = {%s};\n' % ', '.join(map(str,read(symbols['spell_effect_target_class'],'51B'))))
out.append('static const df_u8 g_element_level[] = {%s};\n' % ', '.join(map(str,read(0x17A8B2,'256B'))))
import json
def text(pointer):
    a = pointer
    out_bytes = bytearray()
    while True:
        b = read(a,'B')[0]
        if b == 0: break
        out_bytes.append(b); a += 1
    return json.dumps(out_bytes.decode('cp437'))
sub_rows = []
for t in range(51):
    pointers = read(symbols['spell_effect_subtype_names']+t*48,'12I')
    sub_rows.append('    {' + ', '.join('0' if p == 0 else text(p) for p in pointers) + '},\n')
out.append('static const char *const g_effect_sub_name[51][12] = {\n' + ''.join(sub_rows) + '};\n')
out.append(array('g_undead_daedra','undead_daedra_ids','14B','df_u8'))
out.append('static const DiseaseDef g_disease[17] = {\n')
for i in range(17):
    a=symbols['disease_table']+i*47
    out.append('    {%d, {%s}, %s},\n' % (read(a,'B')[0],', '.join(map(str,read(a+1,'11h'))),', '.join(map(str,read(a+23,'4h')))))
out.append('};\n')
Path('src/game/dagger/tables/magicdata.h').write_text(''.join(out))
